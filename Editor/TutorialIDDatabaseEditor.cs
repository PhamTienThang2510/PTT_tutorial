using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace PTT.Tutorial.Editor
{
    [CustomEditor(typeof(TutorialIDDatabase))]
    public class TutorialIDDatabaseEditor : UnityEditor.Editor
    {
        public override void OnInspectorGUI()
        {
            var db = (TutorialIDDatabase)target;

            EditorGUILayout.HelpBox(
                "IDs are plain strings. Renaming an ID here does NOT rename it on buttons and steps " +
                "already using it — they will show ⚠ in the Inspector.", MessageType.Info);

            DrawDefaultInspector();

            foreach (string problem in Validate(db))
                EditorGUILayout.HelpBox(problem, MessageType.Warning);

            EditorGUILayout.Space();
            if (GUILayout.Button("Generate Constants"))
                GenerateConstants(db);
        }

        static IEnumerable<string> Validate(TutorialIDDatabase db)
        {
            foreach (var (name, list) in new[] { ("Button", db.buttonIDs), ("Sequence", db.sequenceIDs) })
            {
                var seen = new HashSet<string>();
                foreach (string id in list)
                {
                    if (string.IsNullOrWhiteSpace(id)) yield return $"{name} IDs: empty entry.";
                    else if (!seen.Add(id)) yield return $"{name} IDs: '{id}' is listed twice.";
                }
            }
        }

        /// <summary>
        /// Writes a C# file with one constant per ID, so code can use
        /// TutorialSequenceIDs.seq_main_menu instead of a typed string.
        /// </summary>
        public static void GenerateConstants(TutorialIDDatabase db)
        {
            string path = db.constantsFilePath;
            if (string.IsNullOrWhiteSpace(path) || !path.StartsWith("Assets/") || !path.EndsWith(".cs"))
            {
                Debug.LogError("Constants file path must be inside Assets/ and end with .cs", db);
                return;
            }

            bool ns = !string.IsNullOrWhiteSpace(db.constantsNamespace);
            string indent = ns ? "    " : "";
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> by TutorialIDDatabase. Do not edit: click 'Generate Constants' again. </auto-generated>");
            if (ns) sb.AppendLine($"namespace {db.constantsNamespace}\n{{");
            AppendClass(sb, indent, "TutorialButtonIDs", db.buttonIDs);
            sb.AppendLine();
            AppendClass(sb, indent, "TutorialSequenceIDs", db.sequenceIDs);
            if (ns) sb.AppendLine("}");

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, sb.ToString());
            AssetDatabase.ImportAsset(path);
            Debug.Log($"Tutorial ID constants written to {path}", db);
        }

        static void AppendClass(StringBuilder sb, string indent, string className, List<string> ids)
        {
            sb.AppendLine($"{indent}public static class {className}");
            sb.AppendLine($"{indent}{{");
            var used = new HashSet<string>();
            foreach (string id in ids)
            {
                if (string.IsNullOrWhiteSpace(id)) continue;
                string name = ToIdentifier(id);
                if (!used.Add(name)) continue;
                sb.AppendLine($"{indent}    public const string {name} = \"{id.Replace("\\", "\\\\").Replace("\"", "\\\"")}\";");
            }
            sb.AppendLine($"{indent}}}");
        }

        static string ToIdentifier(string id)
        {
            string name = Regex.Replace(id.Trim(), @"[^A-Za-z0-9_]", "_");
            if (char.IsDigit(name[0])) name = "_" + name;
            return name;
        }
    }
}
